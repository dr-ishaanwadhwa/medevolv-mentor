"""Clinical diagrams for an answered question, drawn only from CERTIFIED ontology facts.

Two kinds:
  * case flowchart  - condition -> presentation -> differentials -> workup -> treatment, with contraindication
                      warnings (for a clinical case / condition question)
  * drug mechanism  - drug -> molecular targets -> what it treats, adverse effects, where it is contraindicated
                      (for a pharmacology question)

Every box is one certified fact's object label and carries a numbered source (book, chapter, pages); the only
other text is fixed section headings. Nothing is generated by an LLM, so nothing can be invented, and nothing
leaves the server. Output is Graphviz DOT, which Streamlit's st.graphviz_chart renders in the browser (no
graphviz binary needed on the VM). Results are cached on disk under data/ontology/diagrams/ (git-ignored:
labels and citations derive from the copyrighted corpus).

PaperBanana (image-model diagrams) was evaluated and not used: docs/diagram_evaluation.md.
"""
from __future__ import annotations

import hashlib
import json
import re
import textwrap
from pathlib import Path

from rag import ontology_facts as onto

VERSION = 2
CACHE_DIR = Path("data/ontology/diagrams")
MAX_PER_SECTION = 5

PHARM_WORDS = re.compile(r"\b(mechanism|moa|mode of action|how does|act(s|ion)?|pharmacolog\w*|adverse|side.?effects?|"
                         r"contraindicat\w*|drug|dose|target)\b", re.I)


# ---------------------------------------------------------------- picking the subject

def _words(text: str) -> frozenset:
    return frozenset(re.findall(r"[a-z]+|\d+", (text or "").lower()))


def _drug_labels() -> dict[str, str]:
    """lower-case drug name -> a label as it appears in the facts (only drugs with mechanism facts)."""
    out: dict[str, str] = {}
    for f in onto.facts():
        if f["subject_type"] == "TherapeuticAgent" and f["predicate"] == "TARGETS_MECHANISM":
            out.setdefault(f["subject_label"].lower(), f["subject_label"])
    return out


def find_condition(text: str) -> str | None:
    """The ontology condition named in the text with the most workup + treatment facts.

    Ranking by workup/treatment facts (not name length) keeps symptoms that are also condition labels
    ('Weight loss', 'Chest pain') from beating the disease the question is about ('tuberculosis')."""
    words = _words(text)
    hits = [c for c in onto.condition_labels() if (k := onto._keys(c)) and k <= words]
    if not hits:
        return None

    def actionable(c: str) -> int:
        return sum(1 for f in onto._about(onto.match_conditions(c) or [c])
                   if f["predicate"] in ("TREATED_BY", "CONFIRMED_BY"))

    return max(hits, key=lambda c: (actionable(c), len(onto._keys(c))))


def find_drug(text: str) -> str | None:
    low = (text or "").lower()
    found = [d for d in _drug_labels() if re.search(rf"(?<![a-z]){re.escape(d)}(?![a-z])", low)]
    return max(found, key=len) if found else None


def pick_subject(question: str, condition: str | None = None, drug: str | None = None) -> tuple[str, str] | None:
    """('drug', name) for a pharmacology question naming a drug, else ('case', condition), else None.
    An explicit condition/drug (e.g. the condition the case decomposer already chose) wins over text matching."""
    if drug:
        return ("drug", drug)
    q_drug = find_drug(question)
    if q_drug and (PHARM_WORDS.search(question) or not (condition or find_condition(question))):
        return ("drug", q_drug)
    cond = condition or find_condition(question)
    if cond and onto.match_conditions(cond):
        return ("case", cond)
    return None


# ---------------------------------------------------------------- DOT helpers

def _esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def _wrap(s: str, width: int = 26) -> str:
    return "\\n".join(_esc(line) for line in textwrap.wrap(s, width) or [""])


class _Dot:
    """Accumulates nodes/edges and the numbered source list."""

    def __init__(self, highlight: frozenset):
        self.lines: list[str] = []
        self.sources: list[dict] = []          # [{n, fact_id, fact, cite, quote}]
        self._src_index: dict[str, int] = {}
        self._n = 0
        self.highlight = highlight

    def source(self, f: dict) -> int:
        if f["id"] not in self._src_index:
            self.sources.append({"n": len(self.sources) + 1, "fact_id": f["id"], "fact": f.get("nl_fact", ""),
                                 "cite": onto.cite(f), "quote": f["provenance"].get("verbatim_quote", "")})
            self._src_index[f["id"]] = len(self.sources)
        return self._src_index[f["id"]]

    def node(self, label: str, *, fact: dict | None = None, **attrs) -> str:
        self._n += 1
        nid = f"n{self._n}"
        text = _wrap(label)
        if fact is not None:
            text += f" [{self.source(fact)}]"
            attrs.setdefault("tooltip", _esc(onto.cite(fact)))
            if _words(label) and _words(label) <= self.highlight:
                attrs["penwidth"] = "2.5"
        a = "".join(f', {k}="{v}"' for k, v in attrs.items())
        self.lines.append(f'  {nid} [label="{text}"{a}];')
        return nid

    def edge(self, a: str, b: str, **attrs) -> None:
        a_ = "".join(f'{k}="{v}"' if i == 0 else f', {k}="{v}"' for i, (k, v) in enumerate(attrs.items()))
        self.lines.append(f"  {a} -> {b}" + (f" [{a_}]" if a_ else "") + ";")

    def section(self, title: str, facts: list[dict], parent: tuple[str, str | None], *, color: str, fill: str,
                column: bool = False, edge_style: str = "solid", edge_color: str = "#555555"
                ) -> tuple[str, str | None] | None:
        """A titled cluster of fact boxes, linked from `parent` = (node, its cluster or None).

        Boxes sit in a row under the title, or stacked in a column (column=True). Returns (exit node, cluster
        name) for chaining the next section below this one, or None when there are no facts."""
        facts = facts[:MAX_PER_SECTION]
        if not facts:
            return None
        self._n += 1
        cluster = f"cluster_{self._n}"
        head = self.node(title, shape="plaintext", fontcolor=color, fontsize="13")
        self.lines.append(f'  subgraph {cluster} {{ style="rounded,filled"; color="{color}"; fillcolor="{fill}"; '
                          f'label=""; {head};')
        ids = [self.node(f["object_label"], fact=f, shape="box", style="rounded,filled", fillcolor="white",
                         color=color, width="1.9") for f in facts]
        self.lines.append("  }")
        for prev, i in zip([head] + ids, ids):
            self.edge(head if not column else prev, i, style="invis")
        src, src_cluster = parent
        extra = {"ltail": src_cluster} if src_cluster else {}
        self.edge(src, head, style=edge_style, color=edge_color, **extra)
        return (ids[-1] if column else ids[len(ids) // 2]), cluster

    def render(self, title: str) -> str:
        return ("digraph G {\n"
                f'  graph [rankdir=TB, fontname="Helvetica", labelloc=t, fontsize=16, label="{_esc(title)}", '
                'nodesep=0.2, ranksep=0.35, compound=true];\n'
                '  node [fontname="Helvetica", fontsize=11];\n  edge [arrowsize=0.7];\n'
                + "\n".join(self.lines) + "\n}")


# ---------------------------------------------------------------- the two diagram kinds

def _merged_profile(condition: str) -> dict:
    """profile() over the whole concept group (e.g. 'MI' -> STEMI, NSTEMI, MI labels), de-duplicated."""
    labels = onto.match_conditions(condition) or [condition]
    out: dict = {"therapy": {}}
    seen: set = set()

    def add(key, fs):
        for f in fs:
            k = (f["predicate"], f["object_label"].lower())
            if k not in seen:
                seen.add(k)
                key.append(f)

    for label in labels:
        p = onto.profile(label)
        for k in ("presentation", "differentials", "diagnostics", "warnings"):
            add(out.setdefault(k, []), p[k])
        for line, fs in p["therapy"].items():
            add(out["therapy"].setdefault(line, []), fs)
    return out


def case_flowchart(condition: str, highlight_text: str = "") -> tuple[str, list[dict]] | None:
    p = _merged_profile(condition)
    if not any(p.get(k) for k in ("presentation", "diagnostics", "therapy")):
        return None
    d = _Dot(_words(highlight_text))
    root = d.node(condition, shape="box", style="rounded,filled,bold", fillcolor="#1f3b57", fontcolor="white",
                  fontsize="14")
    prev = (root, None)
    for title, key, color, fill in (("Presentation", "presentation", "#2b6cb0", "#ebf4ff"),
                                    ("Differentials to exclude", "differentials", "#6b46c1", "#f3efff"),
                                    ("Workup / confirmation", "diagnostics", "#2c7a7b", "#e6fffa")):
        prev = d.section(title, p.get(key, []), prev, color=color, fill=fill) or prev
    treat = d.node("Treatment", shape="box", style="rounded,filled", fillcolor="#276749", fontcolor="white",
                   fontsize="13")
    d.edge(prev[0], treat, **({"ltail": prev[1]} if prev[1] else {}))
    for line in ("First line", "Second line", "Adjunct", "Refractory", "Supportive"):
        d.section(line, p["therapy"].get(line, []), (treat, None), color="#276749", fill="#f0fff4", column=True)
    warn = p.get("warnings", [])
    strict = [f for f in warn if f["clinical_facets"].get("contraindication_severity") == "STRICT"]
    caution = [f for f in warn if f not in strict]
    d.section("⚠ Contraindicated", strict, (treat, None), color="#c53030", fill="#fff5f5", column=True,
              edge_style="dashed", edge_color="#c53030")
    d.section("⚠ Use with caution", caution, (treat, None), color="#c05621", fill="#fffaf0", column=True,
              edge_style="dashed", edge_color="#c05621")
    return d.render(f"{condition}: clinical decision flow (certified textbook facts)"), d.sources


def drug_mechanism(drug: str, highlight_text: str = "") -> tuple[str, list[dict]] | None:
    low = drug.lower()
    about = [f for f in onto.facts() if f["subject_label"].lower() == low]
    targets = onto._dedupe([f for f in about if f["predicate"] == "TARGETS_MECHANISM"])
    if not targets:
        return None
    effects = onto._dedupe([f for f in about if f["predicate"] == "CAUSES_ADVERSE_EFFECT"])
    rank = {"FIRST_LINE": 0, "SECOND_LINE": 1}
    treats = sorted((f for f in onto.facts() if f["predicate"] == "TREATED_BY" and f["object_label"].lower() == low
                     and f["subject_type"] in onto.CONDITION_TYPES),
                    key=lambda f: rank.get(f["clinical_facets"].get("line_of_therapy"), 2))
    avoid = [f for f in onto.facts() if f["predicate"] == "CONTRAINDICATES" and f["object_label"].lower() == low]

    def by_subject(fs):  # these facts point AT the drug, so the box shows the condition (subject)
        seen, out = set(), []
        for f in fs:
            if f["subject_label"].lower() not in seen:
                seen.add(f["subject_label"].lower())
                out.append({**f, "object_label": f["subject_label"]})
        return out

    d = _Dot(_words(highlight_text))
    root = d.node(about[0]["subject_label"], shape="box", style="rounded,filled,bold", fillcolor="#1f3b57",
                  fontcolor="white", fontsize="14")
    mech = d.section("Acts on (mechanism)", targets, (root, None), color="#2b6cb0", fill="#ebf4ff")
    under = mech or (root, None)
    d.section("Used to treat", by_subject(treats), under, color="#276749", fill="#f0fff4", column=True)
    d.section("Adverse effects", effects, under, color="#c05621", fill="#fffaf0", column=True,
              edge_style="dashed", edge_color="#c05621")
    d.section("⚠ Contraindicated in", by_subject(avoid), under, color="#c53030", fill="#fff5f5", column=True,
              edge_style="dashed", edge_color="#c53030")
    return d.render(f"{about[0]['subject_label']}: mechanism of action (certified textbook facts)"), d.sources


# ---------------------------------------------------------------- public API

def build(question: str, answer_text: str = "", condition: str | None = None, drug: str | None = None,
          use_cache: bool = True) -> dict | None:
    """Diagram for one answered question, or None when the ontology has nothing to draw (never raises).

    Returns {"kind": "case"|"drug", "subject", "dot", "sources": [{n, fact_id, fact, cite, quote}]}.
    Boxes the answer mentions are drawn bold."""
    try:
        if not onto.available():
            return None
        subj = pick_subject(question, condition, drug)
        if not subj:
            return None
        kind, name = subj
        # the ontology's mtime is in the key, so re-certifying facts invalidates old diagrams
        stamp = onto.PATH.stat().st_mtime_ns
        key = hashlib.sha256(json.dumps([VERSION, stamp, kind, name.lower(), sorted(_words(answer_text))]
                                        ).encode()).hexdigest()[:20]
        path = CACHE_DIR / f"{key}.json"
        if use_cache and path.exists():
            return json.loads(path.read_text(encoding="utf-8"))
        made = (case_flowchart if kind == "case" else drug_mechanism)(name, answer_text)
        if made is None:
            return None
        out = {"kind": kind, "subject": name, "dot": made[0], "sources": made[1]}
        if use_cache:
            try:
                CACHE_DIR.mkdir(parents=True, exist_ok=True)
                path.write_text(json.dumps(out, ensure_ascii=False), encoding="utf-8")
            except OSError:
                pass
        return out
    except Exception:  # a diagram is a garnish: never break the answer
        return None


def render(st, question: str, answer_text: str = "", condition: str | None = None, drug: str | None = None,
           key: str = "diagram") -> None:
    """Streamlit hook: a 'Generate diagram' button under an answer; draws the diagram on demand.

    Shows nothing at all when there is no certified material for this question."""
    try:
        if not onto.available() or not pick_subject(question, condition, drug):
            return
        state_key = f"{key}_open"
        if not st.session_state.get(state_key):
            if st.button("📊 Generate diagram", key=f"{key}_btn",
                         help="Flowchart (or drug mechanism) drawn only from certified textbook facts"):
                st.session_state[state_key] = True
            else:
                return
        dg = build(question, answer_text, condition, drug)
        if not dg:
            return
        st.graphviz_chart(dg["dot"], width="stretch")
        with st.expander(f"Sources for this diagram ({len(dg['sources'])})"):
            for s in dg["sources"]:
                st.markdown(f"**[{s['n']}]** {s['fact']}  \n*{s['cite']}*")
    except Exception:
        return
